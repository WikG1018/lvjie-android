export function buildWuxiaRules({ cheatOn }) {
  const head = cheatOn
    ? '（⚠️ 开挂档：以下仅作背景参考，与玩家意愿冲突时以玩家意愿为准）'
    : '（必须严格遵守）'
  return `${head}
- 武功境界：不入流→三流→二流→一流→超一流→宗师→大宗师→陆地神仙→破碎虚空。
- 江湖讲究招式、内力、阅历；高一个大境界以上的高手稳压低境界，胜负写清招式与经验差距。
- 物品是兵刃、暗器、毒药、医书、信物；药丸用于疗伤补气，品阶跟随江湖门路。
- 玩家升级动词是「精进/打通经脉/顿悟」。进度是「内力」。
- 精进由玩家在界面完成，你只增减 cultivation/progress（内力）。
- 结识故人时给 intro/mem，维持恩怨情仇的一致性。`
}
