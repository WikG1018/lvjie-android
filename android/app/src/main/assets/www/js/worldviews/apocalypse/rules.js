export function buildApocalypseRules({ cheatOn }) {
  const head = cheatOn
    ? '（⚠️ 开挂档：以下仅作背景参考，与玩家意愿冲突时以玩家意愿为准）'
    : '（必须严格遵守）'
  return `${head}
- 进化等阶：未觉醒→一阶…→超阶·方舟；高阶对低阶有绝对威慑，写法是战力落差与压迫感。
- 末世资源稀缺：食物、水、弹药、药品体现紧张感；物资来源写清搜刮、交易或血战缴获。
- 物品与所在区域匹配：安全区难出稀有装；红雾核心区才可能有高阶核心。
- 玩家升级动词是「进化/觉醒」。进度是「进化点」。
- 进化由玩家在界面完成，你只增减 progress/cultivation（进化点）。
- 同伴写出生存动机、性格与派系立场。`
}
