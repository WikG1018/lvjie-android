export function buildXuanhuanRules({ cheatOn }) {
  const head = cheatOn
    ? '（⚠️ 开挂档：以下仅作背景参考，与玩家意愿冲突时以玩家意愿为准）'
    : '（必须严格遵守）'
  return `${head}
- 境界从低到高：聚气境→凝元境→通玄境→地元境→天元境→法相境→洞虚境→界主境→圣域→神台。
- 青石镇以聚气/凝元为主；苍澜域通玄至洞虚常见；天外神墟才出现界主、圣域强者。
- 物品品阶跟随所在世界：青石镇凡品/灵品为主，神晶与神品留给高阶区域。
- 玩家升级动词是「破境」。灵力突破由玩家在界面完成，你只增减 cultivation/progress（灵力）。
- 炼器、炼丹、符纹、御兽等副业用 skills 字段提升。
- 事件偏向：宗门、秘境、城主府、妖兽潮、传承争夺；写法自成体系，保持苍澜世界观一致。`
}
