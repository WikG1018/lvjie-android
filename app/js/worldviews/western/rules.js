export function buildWesternRules({ cheatOn }) {
  const head = cheatOn
    ? '（⚠️ 开挂档：以下仅作背景参考，与玩家意愿冲突时以玩家意愿为准）'
    : '（必须严格遵守）'
  return `${head}
- 位阶：学徒→正式→资深→精英→大师→大法师/圣骑士→传奇→史诗→半神→神→主神。
- 魔法体系自洽：魔力、神术、骑士光辉各有来源；物品用银币/金币/魔晶，形态是药剂、卷轴、附魔武装。
- 位阶压制明显：学徒的机遇对应学徒位阶；传奇武装与神域物品出现在相应高阶场景。
- 玩家升级动词是「晋阶」。进度是「魔力/经验」。晋阶由玩家在界面完成，你只增减 progress/cultivation。
- 同伴给出阵营（王国/公会/教会/中立）与人设 intro。`
}
