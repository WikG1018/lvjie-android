export function buildUrbanRules({ cheatOn }) {
  const head = cheatOn
    ? '（⚠️ 开挂档：以下仅作背景参考，与玩家意愿冲突时以玩家意愿为准）'
    : '（必须严格遵守）'
  return `${head}
- 本世界是**现代职场与商战**：金钱、合同、舆论、法律、人设、赛道风口；超自然力量与系统面板一律不存在。
- 社会段位差距体现为资源与话语权；下属对上级保持职场化敬畏，同级平起平坐谈合作。
- 货币：现金/理财/资产三级。大额交易写清名目（融资、股权、版权、项目款）。
- 玩家升级动词是「晋升/上位/拿下」。进度叫「声望经验」。
- 晋升由玩家在界面完成，你只增减 progress/cultivation（声望经验）。
- 专业技能：技术/商业/传媒/法务。物品是装备、资产、课程方法论、证件机会。
- 事件类型：接项目、路演、谈判、跳槽、创业、舆情危机、资本局。`
}
